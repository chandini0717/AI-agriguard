// Helper to find crop by id or name (case-insensitive)
export function findCropByNameOrId(query: string): CropDefinition | undefined {
  const clean = query.trim().toLowerCase();
  return CROPS_DATABASE.find(c =>
    c.id.toLowerCase() === clean ||
    c.name.toLowerCase() === clean ||
    c.name.toLowerCase().includes(clean) ||
    c.teluguName.includes(clean) ||
    c.hindiName.includes(clean)
  );
}

